  function initMobileNav() {
    var hamburgerBtn = document.getElementById("hamburgerBtn");
    var closeBtn = document.getElementById("mobileNavClose");
    var overlay = document.getElementById("mobileNavOverlay");
    var drawer = document.getElementById("mobileNav");

    if (!hamburgerBtn || !drawer || !overlay) return;

    function openDrawer() {
      drawer.classList.add("is-open");
      overlay.classList.add("is-visible");
      drawer.setAttribute("aria-hidden", "false");
      hamburgerBtn.setAttribute("aria-expanded", "true");
      document.body.style.overflow = "hidden";
    }

    function closeDrawer() {
      drawer.classList.remove("is-open");
      overlay.classList.remove("is-visible");
      drawer.setAttribute("aria-hidden", "true");
      hamburgerBtn.setAttribute("aria-expanded", "false");
      document.body.style.overflow = "";
    }

    hamburgerBtn.addEventListener("click", openDrawer);
    overlay.addEventListener("click", closeDrawer);
    if (closeBtn) closeBtn.addEventListener("click", closeDrawer);

    document.addEventListener("keydown", function (event) {
      if (event.key === "Escape" && drawer.classList.contains("is-open")) {
        closeDrawer();
      }
    });

    // Close drawer automatically if resized up to desktop breakpoint.
    window.addEventListener("resize", function () {
      if (window.innerWidth >= 1024 && drawer.classList.contains("is-open")) {
        closeDrawer();
      }
    });
  }

  /* =========================================================
     CONTACT FORM — validation, submission handling.
     Guarded on the presence of #contactForm, so this file is
     safe even if reused elsewhere by accident.
     ========================================================= */
  function initContactForm() {
    var form = document.getElementById("contactForm");
    var messageEl = document.getElementById("contactFormMessage");
    if (!form || !messageEl) return;

    var emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

    var fields = {
      name: { input: document.getElementById("contact-name"), error: document.getElementById("contact-name-error") },
      email: { input: document.getElementById("contact-email"), error: document.getElementById("contact-email-error") },
      subject: { input: document.getElementById("contact-subject"), error: document.getElementById("contact-subject-error") },
      message: { input: document.getElementById("contact-message"), error: document.getElementById("contact-message-error") }
    };

    function validateField(key) {
      var f = fields[key];
      if (!f || !f.input) return true;
      var value = f.input.value.trim();
      var valid = value !== "";

      if (valid && key === "email") {
        valid = emailPattern.test(value);
      }

      f.input.setAttribute("aria-invalid", valid ? "false" : "true");
      if (f.error) {
        f.error.textContent = valid
          ? ""
          : (key === "email" ? "Please enter a valid email address." : "This field is required.");
      }
      return valid;
    }

    Object.keys(fields).forEach(function (key) {
      var f = fields[key];
      if (!f.input) return;
      f.input.addEventListener("blur", function () { validateField(key); });
      f.input.addEventListener("input", function () {
        if (f.input.getAttribute("aria-invalid") === "true") validateField(key);
      });
    });

    form.addEventListener("submit", function (event) {
      event.preventDefault();
      messageEl.classList.remove("is-error", "is-success");

      var allValid = true;
      var firstInvalidInput = null;
      Object.keys(fields).forEach(function (key) {
        var ok = validateField(key);
        if (!ok && !firstInvalidInput && fields[key].input) {
          firstInvalidInput = fields[key].input;
        }
        allValid = allValid && ok;
      });

      if (!allValid) {
        messageEl.textContent = "Please fix the highlighted fields above.";
        messageEl.classList.add("is-error");
        if (firstInvalidInput) firstInvalidInput.focus();
        return;
      }

      // Placeholder submission handler.
      // Replace with a real API call once a backend endpoint is connected, e.g.:
      //   fetch("/api/contact", {
      //     method: "POST",
      //     headers: { "Content-Type": "application/json" },
      //     body: JSON.stringify(Object.fromEntries(new FormData(form)))
      //   });

      messageEl.textContent = "Thanks \u2014 your message has been received. We'll be in touch soon.";
      messageEl.classList.add("is-success");
      form.reset();
      Object.keys(fields).forEach(function (key) {
        if (fields[key].input) fields[key].input.setAttribute("aria-invalid", "false");
        if (fields[key].error) fields[key].error.textContent = "";
      });
    });
  }

